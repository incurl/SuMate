// Package curated holds the hand-written knowledge base of SuMate
// (东坡嘴替): the concept lexicon, the keyword tables that link verse
// imagery to semantic concepts, and the per-verse overrides for the verses
// that carry the most weight in the product.
package curated

// Concept is one semantic concept in the lexicon.
type Concept struct {
	// Key is the stable machine key.
	Key string `json:"key"`
	// Name is the Chinese display name.
	Name string `json:"name"`
	// Surface is the literal meaning of the concept.
	Surface string `json:"surface"`
	// Deep is the extended artistic conception.
	Deep string `json:"deep"`
	// Philosophy is the hidden philosophical connotation.
	Philosophy string `json:"philosophy"`
	// Attitude is the implied attitude toward life.
	Attitude string `json:"attitude"`
	// Polarity is the emotional colour: positive / neutral / melanchol.
	Polarity string `json:"polarity"`
	// Emotions are the emotion keys of this concept.
	Emotions []string `json:"emotions"`
	// Tangents are the Dongpo temperaments this concept expresses.
	Tangents []string `json:"tangents"`
	// Tags are the tag node ids this concept maps to.
	Tags []string `json:"tags"`
	// Keywords are the surface words that trigger the concept.
	Keywords []string `json:"keywords"`
}

// ConceptKey identifies a concept in the lexicon.
type ConceptKey = string

// Concepts returns the full concept lexicon, keyed by concept key.
//
// The lexicon is the bridge between classical imagery and modern feeling:
// every keyword is a concrete image that appears in Su Dongpo's ci, and every
// concept turns that image into a machine-readable semantic unit that the
// matcher can score against.
func Concepts() map[ConceptKey]Concept {
	c := map[ConceptKey]Concept{}
	for _, x := range conceptList {
		c[x.Key] = x
	}
	return c
}

